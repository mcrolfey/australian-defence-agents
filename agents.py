"""
Multi-agent Australian criminal defence analysis using a local LLM in LM Studio.

Pipeline (each agent is one LLM call that sees the case + earlier agents' work):
  1. Charge Analyst      - identifies the offence/legislation and its elements
  2. Defence Strategist  - legal defences and how each element can be challenged
  3. Procedure Reviewer  - police procedure, evidence admissibility, technical issues
  4. Diversion Advisor   - non-conviction outcomes, diversion, plea/sentencing options
  5. Critic              - stress-tests the above, flags weak or wrong points
  6. Case Lead           - final plan of action

NOT LEGAL ADVICE. Output is general information to help someone prepare to
talk to a lawyer / Legal Aid.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

JURISDICTIONS = {
    "NSW": "New South Wales (e.g. Crimes Act 1900 (NSW), Road Transport Act 2013, Crimes (Sentencing Procedure) Act 1999 s10, Mental Health and Cognitive Impairment Forensic Provisions Act 2020 s14, Evidence Act 1995 (NSW), LEPRA 2002)",
    "VIC": "Victoria (e.g. Crimes Act 1958 (Vic), Road Safety Act 1986, Sentencing Act 1991, Criminal Procedure Act 2009 s59 diversion, Evidence Act 2008 (Vic))",
    "QLD": "Queensland (e.g. Criminal Code 1899 (Qld), Transport Operations (Road Use Management) Act 1995, Penalties and Sentences Act 1992 s12 no conviction recorded, PPRA 2000, Drug Diversion)",
    "WA": "Western Australia (e.g. Criminal Code Act Compilation Act 1913 (WA), Road Traffic Act 1974, Sentencing Act 1995 spent convictions / s45, Criminal Investigation Act 2006)",
    "SA": "South Australia (e.g. Criminal Law Consolidation Act 1935 (SA), Road Traffic Act 1961, Sentencing Act 2017, Summary Offences Act 1953)",
    "TAS": "Tasmania (e.g. Criminal Code Act 1924 (Tas), Police Offences Act 1935, Sentencing Act 1997, Evidence Act 2001 (Tas))",
    "ACT": "Australian Capital Territory (e.g. Criminal Code 2002 (ACT), Crimes Act 1900 (ACT), Crimes (Sentencing) Act 2005, Evidence Act 2011 (ACT))",
    "NT": "Northern Territory (e.g. Criminal Code Act 1983 (NT), Traffic Act 1987, Sentencing Act 1995, Youth Justice Act diversion)",
    "CTH": "Commonwealth (e.g. Criminal Code Act 1995 (Cth), Crimes Act 1914 (Cth) s19B discharge without conviction)",
}

DISCLAIMER = (
    "This is general legal information generated by an AI model, not legal advice. "
    "It may be wrong or out of date. Speak to a lawyer, your state Legal Aid "
    "commission, or an Aboriginal Legal Service before court."
)

GROUND_RULES = """You are part of a team of Australian criminal defence specialists.
Rules:
- Apply the law of the stated jurisdiction. Cite specific Acts and sections where you are confident; say "verify" if unsure. Never invent case names.
- Prosecution must prove every element beyond reasonable doubt; look for every legitimate way it may fail.
- Only lawful strategies: challenging evidence, defences, procedure, negotiation, diversion, sentencing submissions. Never suggest lying, destroying evidence, contacting witnesses improperly, or failing to attend court.
- Be concrete and practical. Use short headings and bullet points.
"""


@dataclass
class Case:
    charges: str
    jurisdiction: str
    location: str = ""
    facts: str = ""
    age: str = ""
    priors: str = ""

    def describe(self) -> str:
        j = JURISDICTIONS.get(self.jurisdiction.upper(), self.jurisdiction)
        return (
            f"JURISDICTION: {j}\n"
            f"LOCATION / COURT: {self.location or 'not stated'}\n"
            f"CHARGES: {self.charges}\n"
            f"ACCUSED AGE: {self.age or 'not stated'}\n"
            f"PRIOR RECORD: {self.priors or 'not stated'}\n"
            f"FACTS AS DESCRIBED BY THE ACCUSED: {self.facts or 'not provided'}"
        )


@dataclass
class Agent:
    name: str
    task: str
    max_tokens: int = 2500


AGENTS = [
    Agent("Charge Analyst",
          "Identify each charge: the likely legislation and section, summary vs indictable, "
          "maximum penalty, and list every ELEMENT the prosecution must prove. Note any "
          "ambiguity in how the charge is described."),
    Agent("Defence Strategist",
          "For each charge, go element by element and explain how the defence could argue "
          "the prosecution cannot prove it. Then list available statutory and common-law "
          "defences (e.g. honest and reasonable mistake of fact, self-defence, necessity, "
          "duress, claim of right, mental impairment, lawful excuse) and when each applies "
          "on these facts. Rank the strongest arguments."),
    Agent("Procedure Reviewer",
          "Identify procedural and evidentiary issues: legality of stop/search/arrest, "
          "cautions and right to silence, recording of interviews, breath/drug test "
          "procedure and time limits, identification evidence, chain of custody, "
          "discretionary exclusion of improperly obtained evidence (e.g. s138 Evidence Act "
          "in uniform-evidence states), limitation periods, defects in the charge sheet. "
          "List what documents to request (brief of evidence, body-cam, CCTV)."),
    Agent("Diversion Advisor",
          "Explain outcomes that avoid a conviction or minimise penalty in this jurisdiction: "
          "withdrawal/representations to police to drop or downgrade charges, diversion "
          "programs, mental health diversion, dismissal without conviction, good behaviour "
          "bonds, plea negotiation to lesser charges, and what material helps (character "
          "references, apology letter, counselling, traffic offender program). Note "
          "eligibility and how the accused's age/priors affect it."),
    Agent("Critic",
          "Critically review the team's analysis above. Point out legal errors, wrong "
          "jurisdiction law, overconfident claims, weak arguments, and important things "
          "missed. Be blunt and specific.", 1500),
    Agent("Case Lead",
          "Write the DEFENCE STRATEGY REPORT, using everything above and applying the Critic's "
          "corrections. The goal is to get the charges withdrawn, dismissed or defended "
          "successfully, and failing that to avoid a conviction being recorded. Use exactly "
          "these markdown headings:\n"
          "## 1. Charges and Elements (table: charge | legislation | max penalty | elements)\n"
          "## 2. Primary Defence Strategy (the single best route out of the charges and why)\n"
          "## 3. Ranked Defence Arguments (for each: argument, legal basis, evidence needed, "
          "strength High/Medium/Low)\n"
          "## 4. Getting the Charges Withdrawn or Downgraded (what to put in representations "
          "to police/prosecution)\n"
          "## 5. Evidence to Challenge or Exclude\n"
          "## 6. Fallback: Avoiding a Conviction (diversion, dismissal, no conviction recorded)\n"
          "## 7. Action Plan and Timeline (numbered steps before each court date)\n"
          "## 8. Documents and Evidence Checklist\n"
          "## 9. Questions for Your Lawyer\n"
          "## 10. Realistic Assessment (honest likelihood of each outcome)", 4000),
]


def make_client(base_url: str):
    from openai import OpenAI
    return OpenAI(base_url=f"{base_url.rstrip('/')}/v1", api_key="lm-studio")


def detect_model(client) -> str:
    return client.models.list().data[0].id


_THINK = re.compile(r"<think>.*?</think>", re.S | re.I)


def _clean(text: str) -> str:
    text = _THINK.sub("", text or "")
    # Some thinking models emit channel markers; keep only the final answer.
    if "<|channel|>final" in text:
        text = text.split("<|channel|>final", 1)[1]
    return text.strip()


def call_llm(client, model: str, prompt: str, max_tokens: int, temperature: float = 0.3) -> str:
    # Single user message (no system role) - Gemma models in LM Studio reject system messages.
    resp = client.chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": prompt}],
        max_tokens=max_tokens,
        temperature=temperature,
    )
    msg = resp.choices[0].message
    return _clean(msg.content or getattr(msg, "reasoning_content", "") or "")


def run_case(case: Case, base_url: str = "http://localhost:1234", model: str | None = None,
             on_step=None) -> dict:
    """Run every agent in order. on_step(name, text) is called after each agent."""
    client = make_client(base_url)
    model = model or detect_model(client)
    notes: list[tuple[str, str]] = []
    for agent in AGENTS:
        prior = "\n\n".join(f"=== {n} ===\n{t}" for n, t in notes) or "(none yet)"
        prompt = (
            f"{GROUND_RULES}\nYou are the {agent.name.upper()}.\n\n"
            f"CASE:\n{case.describe()}\n\n"
            f"TEAM WORK SO FAR:\n{prior}\n\n"
            f"YOUR TASK:\n{agent.task}"
        )
        try:
            text = call_llm(client, model, prompt, agent.max_tokens)
        except Exception as e:  # keep the pipeline going
            text = f"[error calling LM Studio: {e}]"
        notes.append((agent.name, text))
        if on_step:
            on_step(agent.name, text)
    return {
        "model": model,
        "steps": [{"agent": n, "output": t} for n, t in notes],
        "final": notes[-1][1],
        "disclaimer": DISCLAIMER,
    }


def build_report(case: Case, result: dict) -> str:
    """Markdown defence strategy report: final plan first, agent working notes as appendix."""
    from datetime import date
    out = [
        "# Defence Strategy Report",
        f"_Generated {date.today():%d %B %Y} by Australian Defence Agents (model: {result['model']})_",
        f"> **Not legal advice.** {DISCLAIMER}",
        "## Case Details\n\n"
        f"- **Charges:** {case.charges}\n"
        f"- **Jurisdiction:** {case.jurisdiction}\n"
        f"- **Location / Court:** {case.location or 'not stated'}\n"
        f"- **Age:** {case.age or 'not stated'}\n"
        f"- **Prior record:** {case.priors or 'not stated'}\n"
        f"- **Facts provided:** {case.facts or 'not provided'}",
        result["final"],
        "---\n# Appendix: Agent Working Notes",
    ]
    out += [f"## {s['agent']}\n\n{s['output']}" for s in result["steps"][:-1]]
    return "\n\n".join(out) + "\n"
